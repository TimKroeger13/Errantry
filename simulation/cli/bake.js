#!/usr/bin/env node
// Takes a champion from an evolution run and writes it to src/tuned.js, which the AI
// uses as its default parameters (console and website alike).
//   node cli/bake.js tuning/evolve-mix2.json
'use strict';
const fs = require('fs');
const path = require('path');

const file = process.argv[2];
if (!file) { console.error('Aufruf: node cli/bake.js <champion.json>'); process.exit(1); }
const champ = JSON.parse(fs.readFileSync(file, 'utf8'));
const policy = Object.assign({}, champ.policy);
// play/flee/start modes are chosen by the presets, not baked in
delete policy.play; delete policy.flee;
if (policy.start !== 'signals' && policy.start !== 'rotate') delete policy.start;
const note = 'Champion aus ' + path.basename(file) + (champ.validatedWin ? ', validiert ' + (champ.validatedWin * 100).toFixed(1) + '% Ø' : '') +
  (champ.perConfig ? ' (' + Object.entries(champ.perConfig).map(([k, v]) => k + ' ' + (v * 100).toFixed(1) + '%').join(', ') + ')' : '');
const src = `// Trained AI parameters (generated by cli/bake.js – do not edit by hand).
// ${note}
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else (root.Errantry = root.Errantry || {}).tuned = factory();
})(typeof globalThis !== 'undefined' ? globalThis : this, function () {
  'use strict';
  return ${JSON.stringify(policy, null, 2).replace(/\n/g, '\n  ')};
});
`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'tuned.js'), src);
console.log('src/tuned.js geschrieben: ' + note);
